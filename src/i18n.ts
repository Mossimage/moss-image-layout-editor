export const messages = { en, zh };

export function parseLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const norm = value.trim().toLowerCase().replace(/_/g, "-");
  if (norm === "en" || norm.startsWith("en-")) return "en";
  if (norm === "zh" || norm.startsWith("zh-")) return "zh";
  return null;
}

/** URL parameter, then the saved choice, then the browser language. */
export function pickLocale(param: string | null, stored: string | null, language: string): Locale {
  return parseLocale(param) ?? parseLocale(stored) ?? parseLocale(language) ?? "en";
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = messages[locale][key];
  if (!vars) return text;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
